#include <iomanip>
#include <iostream>
#include <locale>
#include <string>

int main() {
  std::cout << "==========================================================\n";
  std::cout << "로케일(Locale)이 한글 출력에 미치는 영향\n";
  std::cout << "==========================================================\n\n";

  // =========================================================================
  // 1. 기본 로케일 상태 확인
  // =========================================================================
  std::cout << "[ 1. 기본 상태 ]\n";
  std::cout << "기본 로케일: " << std::locale().name() << std::endl;
  std::cout << "wcout 로케일: " << std::wcout.getloc().name() << std::endl;
  std::cout << "환경변수 LANG: "
            << (getenv("LANG") ? getenv("LANG") : "설정 안됨") << std::endl
            << std::endl;

  // =========================================================================
  // 2. 로케일 없이 한글 출력 시도
  // =========================================================================
  std::cout << "[ 2. 로케일 설정 없이 한글 출력 ]\n";
  std::wstring korean = L"안녕하세요, 세계!";
  std::wcout << L"결과: " << korean << std::endl;
  std::cout
      << "→ 한글이 깨진 문자로 보일 수 있음 (또는 제대로 출력될 수도)\n\n";

  // =========================================================================
  // 3. 로케일을 "C" (기본값)로 명시적 설정
  // =========================================================================
  std::cout << "[ 3. 로케일을 'C'로 명시적 설정 ]\n";
  try {
    std::locale::global(std::locale("C"));
    std::wcout.imbue(std::locale());
    std::cout << "현재 로케일: " << std::locale().name() << std::endl;
    std::wcout << L"결과: " << korean << std::endl;
    std::cout << "→ C 로케일은 ASCII만 지원하므로 한글이 깨짐\n\n";
  } catch (const std::exception& e) {
    std::cout << "에러: " << e.what() << std::endl;
  }

  // =========================================================================
  // 4. 로케일을 "en_US.utf8"로 설정
  // =========================================================================
  std::cout << "[ 4. 로케일을 'en_US.utf8'로 설정 ]\n";
  try {
    std::locale::global(std::locale("en_US.utf8"));
    std::wcout.imbue(std::locale());
    std::cout << "현재 로케일: " << std::locale().name() << std::endl;
    std::wcout << L"결과: " << korean << std::endl;
    std::cout << "→ UTF-8 인코딩을 사용하므로 한글이 제대로 출력됨\n\n";
  } catch (const std::exception& e) {
    std::cout << "에러: " << e.what() << std::endl;
  }

  // =========================================================================
  // 5. 로케일의 구성요소 확인
  // =========================================================================
  std::cout << "[ 5. 로케일의 구성 ]\n";
  std::cout << "로케일 = [언어]_[지역].[인코딩]\n";
  std::cout << "  - en_US.utf8: 영어(US) + UTF-8 인코딩\n";
  std::cout << "  - ko_KR.utf8: 한국어(KR) + UTF-8 인코딩\n";
  std::cout << "  - C / POSIX: 기본 로케일 (ASCII만 지원)\n\n";

  // =========================================================================
  // 6. 인코딩의 역할
  // =========================================================================
  std::cout << "[ 6. 인코딩의 역할 ]\n";
  std::cout << "UTF-8 인코딩:\n";
  std::cout << "  - ASCII: 1바이트 (a = 0x61)\n";
  std::cout << "  - 한글:  3바이트 (안 = 0xec 0x95 0x88)\n\n";

  std::string utf8_korean = u8"안녕";
  std::cout << "  u8\"안녕\"의 바이트: ";
  for (unsigned char c : utf8_korean) {
    std::cout << std::hex << std::setw(2) << std::setfill('0')
              << static_cast<int>(c) << " ";
  }
  std::cout << std::dec << "\n\n";

  // =========================================================================
  // 7. std::locale의 역할
  // =========================================================================
  std::cout << "[ 7. std::locale의 역할 ]\n";
  std::cout << "std::locale은 다음을 정의합니다:\n";
  std::cout << "  1. 문자 인코딩: UTF-8, ASCII, ISO-8859-1 등\n";
  std::cout << "  2. 문자 분류: isalpha(), isdigit() 등의 동작\n";
  std::cout << "  3. 대소문자 변환: tolower(), toupper() 등\n";
  std::cout << "  4. 숫자 형식: 천 단위 구분자, 소수점 표시\n";
  std::cout << "  5. 통화 기호: $, €, ₩ 등\n\n";

  // =========================================================================
  // 8. wcout이 로케일을 사용하는 방식
  // =========================================================================
  std::cout << "[ 8. std::wcout과 로케일의 관계 ]\n";
  std::cout << "std::wcout (wide character output stream):\n";
  std::cout << "  - wchar_t 타입의 문자를 출력\n";
  std::cout << "  - 내부적으로 로케일의 codecvt facet 사용\n";
  std::cout << "  - codecvt: 내부 표현(wchar_t) → 외부 표현(바이트) 변환\n\n";

  std::cout << "로케일이 없으면 (또는 'C' 로케일):\n";
  std::cout << "  - codecvt가 ASCII 범위만 변환 가능\n";
  std::cout << "  - 한글 같은 멀티바이트는 변환 실패 또는 깨짐\n\n";

  std::cout << "로케일이 UTF-8로 설정되면:\n";
  std::cout << "  - codecvt가 wchar_t → UTF-8 바이트로 변환\n";
  std::cout << "  - 한글도 올바른 UTF-8 바이트 시퀀스로 변환\n\n";

  // =========================================================================
  // 9. en_US.utf8이 기본인가?
  // =========================================================================
  std::cout << "[ 9. en_US.utf8이 기본 로케일인가? ]\n";
  std::cout << "아니오. 기본 로케일은 'C' (또는 'POSIX')입니다.\n";
  std::cout << "이유:\n";
  std::cout << "  1. 호환성: 모든 POSIX 시스템에 'C' 로케일은 존재\n";
  std::cout << "  2. 일관성: 프로그램 동작이 플랫폼 독립적\n";
  std::cout << "  3. 성능: 로케일 데이터가 최소한\n\n";

  std::cout << "시스템이 다국어를 지원하려면:\n";
  std::cout << "  1. 환경변수 LANG 설정: export LANG=en_US.UTF-8\n";
  std::cout << "  2. 또는 프로그램에서 std::locale::global() 호출\n\n";

  // =========================================================================
  // 10. en_US.utf8 vs ko_KR.utf8
  // =========================================================================
  std::cout << "[ 10. en_US.utf8과 ko_KR.utf8의 차이 ]\n";
  std::cout << "둘 다 UTF-8 인코딩을 지원하므로 한글 출력은 동일합니다.\n";
  std::cout << "차이점:\n";
  std::cout << "  - en_US.utf8: 영어 지역 설정 (콜레이션, 통화 기호 등)\n";
  std::cout << "  - ko_KR.utf8: 한국어 지역 설정 (콜레이션, 통화 기호 등)\n";
  std::cout << "한글 텍스트 출력만 목적이면 en_US.utf8으로도 충분합니다.\n\n";

  return 0;
}
