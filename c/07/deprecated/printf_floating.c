#include <stdio.h>

int main(void)
{
    printf("%8.5f\n", 1.25);       /* > 1.25000                               */
    printf("%-8.5f\n", 1.25);      /* >1.25000                                */
    printf("%9.3f\n", 3.141592);   /* >    3.142                              */
    printf("%-9.3f\n", 3.141592);  /* >3.142                                  */
    printf("%9f\n", 3.141592);     /* > 3.141592                              */
    printf("%-9f\n", 3.141592);    /* >3.141592                               */
    printf("%10.3e\n", 3.141592);  /* > 3.142e+00                             */
    printf("%-10.3E\n", 3.141592); /* >3.142E+00                              */

    return 0;
}
