#include <stdio.h>

int main(void)
{
    printf("C \n Programming");

    /* several calls may be used to 
       build up an output line in stages */
    printf("A\n");
    printf("Tutorial\n");
    printf("Introduction\n");

    /* concatenate two strings without white spaces */
    printf("Hello, World");
    printf("with no escape sequence");

    return 0;
}
